-- 015_market_price_index.sql
-- 시장 가격지수(시간보정용) — 2026-07-28
--
-- 왜 필요한가 — 운영 DB 실측(611,518행, 2026-07-28)
-- =================================================
-- `fair_price_band` 는 6/12/24/36개월 창의 **중위값**을 적정가로 쓴다. 창 안의 거래는
-- 시점이 흩어져 있는데 아무 보정 없이 섞으므로, 밴드 중위는 사실상 **창의 중간 시점**
-- 가격이다. 창별 거래의 평균 시점을 실측하면:
--
--     6개월창 → 3.2개월 전 · 12개월창 → 5.8개월 전
--    24개월창 → 11.1개월 전 · 36개월창 → 14.4개월 전
--
-- 시장이 멈춰 있으면 문제가 없다. 그런데 멈춰 있지 않았다. 같은 (단지,면적) 그룹 안에서
-- 로그 ₩/㎡ 를 그룹평균으로 뺀 고정효과 지수(2개월 이상 거래한 그룹만)로 실측하면:
--
--     서울 2025-01 0.8981 → 2026-07 1.1371  (+26.6% / 18개월)
--     경기 2025-01 0.9737 → 2026-07 1.0414  (+ 7.0% / 18개월)
--     인천 2025-01 0.9991 → 2026-07 1.0118  (+ 1.3% / 18개월)
--
-- 창 분포(단지+면적 그룹 기준)와 곱하면 **밴드 중위의 체계적 과소평가**가 나온다:
--
--     서울 ≈ 10%  ·  경기 ≈ 3%  ·  인천 ≈ 0.9%
--
-- 서울 단지 하나를 10% 싸게 표시하면 그건 표시 오류로 끝나지 않는다. `reference_price_krw`
-- 가 호가 없는 후보의 **예산 판정 기준가**로 이 값을 쓰기 때문에, 사용자가 실제로는 살 수
-- 없는 단지가 "예산 안"으로 통과한다. 지역마다 오차 크기가 달라(서울 10% vs 인천 0.9%)
-- 서울 후보만 조직적으로 싸 보이는 **지역 편향**까지 생긴다.
--
-- ⛔ 왜 '미등기 최근 실거래' 가 아닌가
-- ====================================
-- "미등기 = 가장 최신 체결가" 라는 가설을 먼저 실측했고, **기각했다**. 미등기 비율은
-- 계약월의 함수일 뿐이다(2026-07 95.6% · 06 87.4% · 05 67.6% · 04 32.4% · 03 7.7% ·
-- 02 2.0% · 2025년 이전 0.4~1.8%). 즉 `registered_at IS NULL` 은 `contract_date >= 최근
-- 3~4개월` 을 **더 나쁘게** 쓴 것이다. 더 나쁜 이유가 셋 있다:
--   (1) 최근 4개월 거래의 34%(등기 완료분)를 이유 없이 버려 표본이 작아진다,
--   (2) 같은 (단지,면적,계약월) 안에서 미등기가 등기보다 +0.5~2.2% 비싸다(선택편향),
--   (3) 새 데이터가 없어도 시간이 지나면 같은 거래가 미등기→등기로 바뀌어 추정치가 흔들린다.
-- 그래서 등기 여부는 쓰지 않고, **계약일 + 지역 지수**로 시점을 보정한다.
--
-- ⛔ 왜 외부(부동산원 주간지수) 가 아닌가
-- ======================================
-- 이 지수는 **우리 trade 테이블에서 직접 계산**한다. 외부 지수는 모집단(전국·주택유형
-- 혼합)과 우리 후보군(수도권 아파트, 우리가 적재한 단지)이 다르고, 새 수집 의존이 생기며,
-- 무엇보다 **검증할 수 없다**. 자체 계산 지수는 표본 수까지 같이 저장해 근거로 제시된다.
--
-- 원칙 (G2)
-- =========
-- · 표본이 모자라는 (지역,월) 은 **행을 만들지 않는다**. NULL 로 두고 상위 지역으로 폴백한다.
-- · 미완결 월(신고 지연으로 표본이 덜 찬 달)은 `is_complete=false` 로 표시하고 기준월로
--   쓰지 않는다. 그래야 "현재 시세"가 아니라 "YYYY-MM 시점 환산"이라고 말할 수 있다.
-- · 지수 값 자체는 **상대값**이다(기준 임의). 두 월의 비(ratio)만 의미가 있다.

BEGIN;

CREATE TABLE IF NOT EXISTS market_price_index (
    -- 지역 코드. 시군구는 5자리('11680'), 시도는 2자리('11').
    -- 시군구 지수가 없으면 시도로 폴백하므로 두 층위를 같은 표에 둔다.
    region_code  text NOT NULL,
    -- 'sigungu' | 'sido' — 어느 층위의 지수인지. 근거 문구에 그대로 나간다.
    scope        text NOT NULL CHECK (scope IN ('sigungu', 'sido')),
    ym           char(7) NOT NULL,              -- 'YYYY-MM'
    -- 고정효과 지수(상대값). exp(median(ln(₩/㎡) - 그룹평균)).
    -- ⚠️ 절대 수준에 의미 없음. index(A)/index(B) 만 쓸 것.
    idx_value    numeric(10,6) NOT NULL CHECK (idx_value > 0),
    -- 이 (지역,월) 지수를 만든 거래 건수. 근거로 노출된다.
    sample_size  integer NOT NULL CHECK (sample_size > 0),
    -- 신고 지연으로 아직 덜 찬 달인가. false 면 **기준월로 쓰지 않는다**.
    is_complete  boolean NOT NULL DEFAULT false,
    -- 계산 방법 식별자. 방법을 바꾸면 값이 달라지므로 섞이지 않게 기록한다.
    method       text NOT NULL,
    computed_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (region_code, scope, ym)
);

COMMENT ON TABLE market_price_index IS
    '지역·월별 아파트 ₩/㎡ 시장지수(자체 계산, 고정효과). 적정가 밴드의 시점 보정에 쓴다. '
    '값은 상대값이며 두 월의 비(ratio)만 의미가 있다. 표본 부족 월은 행이 없다(지어내지 않음).';

COMMENT ON COLUMN market_price_index.idx_value IS
    'exp(median(ln(price/area) - 같은 (complex_id, round(area)) 그룹의 평균)). '
    '그룹 고정효과를 빼서 단지·평형 구성 변화(믹스효과)를 제거한다. 절대 수준은 무의미.';

COMMENT ON COLUMN market_price_index.is_complete IS
    'false = 신고 지연으로 표본이 덜 찬 달. 보정 대상으로는 쓰되 **기준월로는 쓰지 않는다** — '
    '덜 찬 달을 기준으로 삼으면 추정치가 며칠 뒤 이유 없이 바뀐다.';

-- 조회 패턴: (지역, scope) 로 전 기간을 한 번에 읽어 메모리에서 비율 계산.
CREATE INDEX IF NOT EXISTS market_price_index_lookup_idx
    ON market_price_index (region_code, scope, ym DESC);

COMMIT;
