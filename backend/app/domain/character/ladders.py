def percentile_of(score: float, ladder: tuple[float, ...]) -> float:
    """원점수 → 0~100 백분위. **동점은 중간 순위**(midrank)로 센다.

    왜 midrank 인가 — 생활 축은 상위 20%가 전부 정확히 100.0 이다(천장). 동점을 앞에서
    끊으면(bisect_left) 그 20%가 전부 '상위 20%' 가 아니라 '상위 80%' 로 밀려 내려간다.
    뒤에서 끊으면 전부 최상위가 된다. 둘 다 사실이 아니므로 가운데를 쓴다.
    """
    lo = bisect.bisect_left(ladder, score)
    hi = bisect.bisect_right(ladder, score)
    return round((lo + hi) / 2 / len(ladder) * 100, 1)
