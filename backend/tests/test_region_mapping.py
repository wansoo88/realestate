"""region 마스터 → (시군구5, MOLIT 법정동명) 매핑 규칙 (INGEST-3).

왜 이 테스트가 있는가
---------------------
2026-07-26 수도권 확장 적재에서 신규 9,009단지 중 **1,009단지(11%)의 region_code 가
NULL** 로 남았다. 원인은 MOLIT `umdNm` 이 읍·면 지역에서 '오남읍 오남리' 처럼 두
토막으로 오는데, 매핑이 읍면동 레벨만 담고 있어 어디에도 안 걸린 것이다.
region_code 가 없으면 (1) 시군구별 조회에서 사라지고 (2) 부동산원 매칭이 법정동코드
기준이라 매칭도, 그에 기대는 주소 경로 지오코딩도 막힌다 — **지도에서 통째로 사라진다.**

여기서 못박는 것
----------------
1. 동 지역은 예전 그대로 (시군구5, '오남동') 로 걸린다.
2. 읍·면 지역은 **부모 읍·면 이름을 붙인 전체 이름**으로만 걸린다.
3. 리 이름 단독('오남리')으로는 **걸리지 않는다** — 같은 시군구의 '금곡동'/'금곡리'
   처럼 겹치는 이름에 엉뚱한 코드를 붙이지 않기 위해서다.
4. 같은 키가 두 코드를 가리키면 **버린다**(추측하지 않는다).
"""
from __future__ import annotations

from dataclasses import dataclass

from app.ingest.loader import build_region_mapping


@dataclass(frozen=True)
class Row:
    code: str
    sigungu: str
    dong: str


NAMYANGJU = [
    Row("4136010300", "남양주시", "금곡동"),
    Row("4136026200", "남양주시", "오남읍"),
    Row("4136026223", "남양주시 오남읍", "오남리"),
    Row("4136025300", "남양주시", "진접읍"),
    Row("4136025328", "남양주시 진접읍", "금곡리"),
]


def test_동_지역은_한_토막_이름으로_걸린다():
    m = build_region_mapping(NAMYANGJU)
    assert m[("41360", "금곡동")] == "4136010300"
    assert m[("41360", "오남읍")] == "4136026200"


def test_읍면_지역은_읍면과_리를_붙인_이름으로_걸린다():
    # MOLIT umdNm 실제 표기: '오남읍 오남리'
    m = build_region_mapping(NAMYANGJU)
    assert m[("41360", "오남읍 오남리")] == "4136026223"
    assert m[("41360", "진접읍 금곡리")] == "4136025328"


def test_리_이름_단독으로는_걸리지_않는다():
    """'금곡리' 만으로 받으면 같은 시군구의 '금곡동' 과 헷갈린다 — 받지 않는다."""
    m = build_region_mapping(NAMYANGJU)
    assert ("41360", "오남리") not in m
    assert ("41360", "금곡리") not in m


def test_일반구가_있는_시도_부모_읍면만_떼어_쓴다():
    rows = [Row("4146125300", "용인시 처인구", "포곡읍"),
            Row("4146125321", "용인시 처인구 포곡읍", "둔전리")]
    m = build_region_mapping(rows)
    assert m[("41461", "포곡읍 둔전리")] == "4146125321"


def test_같은_키가_두_코드를_가리키면_버린다():
    """애매하면 추측하지 않는다 — 틀린 지역코드는 틀린 지역 통계를 낳는다."""
    rows = [Row("4136026223", "남양주시 오남읍", "오남리"),
            Row("4136026299", "남양주시 오남읍", "오남리")]
    m = build_region_mapping(rows)
    assert ("41360", "오남읍 오남리") not in m


def test_시군구_레벨_행과_모양이_다른_행은_무시한다():
    rows = [Row("4136000000", "남양주시", ""),          # 시군구 레벨(동 없음)
            Row("41360", "남양주시", "오남동"),          # 길이가 10 이 아님
            Row("4136026223", "남양주시", "오남리")]     # 부모가 읍·면이 아님 → 못 씀
    m = build_region_mapping(rows)
    assert m == {}
