/**
 * 한도 산정 가정(`live` | `invest`) — **화면 전체가 읽는 한 곳**.
 *
 * 왜 상수 하나를 파일로 빼나
 * --------------------------
 * 목적에 따라 대출 절대한도·스트레스 가산이 **달라질 수 있고**, 그러면 한도 자체가
 * 달라진다. 그래서 지도(`/map/complexes?purpose=`)와 자금계획(`/affordability`)이 서로
 * 다른 값을 쓰면 같은 단지가 지도에서는 "예산 초과", 자금 패널에서는 "가능"으로 나온다.
 * 두 화면 다 틀리지 않았는데 답이 다르므로 사용자는 어느 쪽도 믿을 수 없게 된다.
 *
 * ⚠️ **오늘은 아직 안 달라진다** (CR38-4). 운영 세율·대출 데이터에 `purpose` 를 조건으로
 *    쓰는 규칙이 **0개**라 `live` 와 `invest` 의 한도가 같다. 백엔드가 그 사실을 테스트로
 *    못박아 두었고(`backend/tests/test_tax_rules_real.py` — 규칙이 생기면 **일부러 깨진다**),
 *    깨지는 날 고칠 자리 목록에 이 파일이 적혀 있다. 그때까지 "달라진다"고 쓰지 않는다.
 *    그래도 값을 흘려보내는 배선은 지금 갖춰 둔다 — 규칙이 생긴 날 배선부터 찾는 것보다
 *    한 줄 바꾸는 편이 낫고, 배선이 없으면 그 어긋남은 화면 어디에도 표시가 없다.
 *
 * 값을 화면마다 리터럴로 적으면 언젠가 한 곳만 바뀐다(그리고 그 사실은 조용하다).
 * 그래서 **여기 하나만 두고 전부 여기서 읽는다** — 투자 모드를 켜는 날 한 줄만 바뀐다.
 *
 * 🔐 이 값은 **비민감 열거값**이다. 금액도, 자산으로 되짚을 수 있는 파생값도 아니므로
 *    URL 쿼리에 실어도 SR32-1 규칙에 걸리지 않는다(`api/client.ts::buildQuery` 통과).
 */
import type { Purpose } from "../api/client";

export type { Purpose };

/**
 * 지금 화면이 쓰는 목적. **실거주(`live`) 고정**이다.
 *
 * 투자(`invest`)는 세율·한도·판단 기준이 달라 별도 화면이 필요하다(2차). 사용자가
 * 고르는 UI 가 생기면 이 상수는 "초기값"이 되고, 선택 값이 지도·자금계획·추천에
 * **동시에** 흘러야 한다 — 한 곳만 바뀌면 위 주석의 어긋남이 그대로 재현된다.
 */
export const DEFAULT_PURPOSE: Purpose = "live";
